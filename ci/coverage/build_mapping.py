# Parse per-test .cov.json files and JIT-LTO activation logs produced by
# collect_coverage.py and write func2tests.json.
#
# Called by ci/coverage/collect_and_map.sh.

import argparse
import json
import sys
from pathlib import Path


# ---------------------------------------------------------------------------
# .cov.json parsing
# ---------------------------------------------------------------------------

def parse_cov_json(cov_path: Path) -> tuple[str, dict[str, set[str]]]:
    """
    Parse one per-test .cov.json file produced by collect_coverage.py.

    Returns (test_name, {repo_relative_source_file: {covered_function_name, ...}}).
    """
    with open(cov_path) as f:
        data = json.load(f)
    test_name = data.get("test_name", "")
    covered = data.get("covered", {})
    return test_name, {src: set(fns) for src, fns in covered.items()}


# ---------------------------------------------------------------------------
# JIT-LTO integration
# ---------------------------------------------------------------------------

def load_jit_sources(jit_sources_path: Path) -> dict[str, dict]:
    """
    Load jit_lto_sources.json produced by the coverage cmake build.
    Returns {fragment_tag: {"kernel_source": ..., "matrix_source": ...}}.
    """
    if not jit_sources_path.exists():
        return {}
    with open(jit_sources_path) as f:
        data = json.load(f)
    return data.get("fragment_tags", {})


def apply_jit_lto_logs(
    coverage_dir: Path,
    jit_sources: dict[str, dict],
    file2tests: dict[str, set[str]],
    skip_tests: set[str] | None = None,
) -> None:
    """
    For each per-test .jit.log, look up each activated fragment key in
    jit_sources and extend file2tests with the kernel_source and
    matrix_source paths.
    """
    if not jit_sources:
        return

    for jit_log in coverage_dir.glob("*.jit.log"):
        cov_path = jit_log.with_suffix(".cov.json")
        if not cov_path.exists():
            continue
        test_name, _ = parse_cov_json(cov_path)
        if not test_name:
            continue
        if skip_tests and test_name in skip_tests:
            continue

        for fragment_key in jit_log.read_text().splitlines():
            fragment_key = fragment_key.strip()
            if not fragment_key or fragment_key not in jit_sources:
                continue
            entry = jit_sources[fragment_key]
            for src_key in ("kernel_source", "matrix_source"):
                path = entry.get(src_key, "")
                if path:
                    file2tests.setdefault(path, set()).add(test_name)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _peek_test_name(cov_path: Path) -> str:
    """Read only the test_name field from a .cov.json without loading covered data."""
    try:
        with open(cov_path) as f:
            return json.load(f).get("test_name", "")
    except Exception:
        return ""


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Build func2tests.json from per-test .cov.json files and JIT-LTO "
            "activation logs produced by collect_coverage.py."
        )
    )
    parser.add_argument(
        "--coverage-dir",
        required=True,
        help="Directory containing per-test .cov.json and .jit.log files "
             "(typically <build-dir>/per_test_coverage)",
    )
    parser.add_argument(
        "--jit-sources",
        default="cpp/build/coverage/jit_lto_sources.json",
        help="Path to jit_lto_sources.json generated by the coverage cmake build",
    )
    parser.add_argument(
        "--repo-root",
        default=".",
        help="Repository root (paths in func2tests.json are relative to this)",
    )
    parser.add_argument(
        "--output",
        default="func2tests.json",
        help="Output path for func2tests.json",
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help="Merge into an existing func2tests.json rather than overwriting it; "
             "skips .cov.json files whose test_name is already recorded",
    )
    args = parser.parse_args()

    coverage_dir = Path(args.coverage_dir).resolve()
    jit_sources_path = Path(args.jit_sources).resolve()
    output_path = Path(args.output)

    if not coverage_dir.exists():
        sys.exit(f"ERROR: coverage dir does not exist: {coverage_dir}")

    cov_files = sorted(coverage_dir.glob("*.cov.json"))
    if not cov_files:
        sys.exit(f"ERROR: no .cov.json files found in {coverage_dir}")

    # {gcov_function_name: {test_name, ...}}
    func2tests: dict[str, set[str]] = {}
    # {repo_relative_source_file: {test_name, ...}}
    file2tests: dict[str, set[str]] = {}
    already_recorded: set[str] = set()

    if args.update and output_path.exists():
        print(f"Loading existing mapping from {output_path} ...", flush=True)
        with open(output_path) as f:
            existing = json.load(f)
        for fn, tests in existing.get("functions", {}).items():
            func2tests[fn] = set(tests)
            already_recorded.update(tests)
        for src, tests in existing.get("files", {}).items():
            file2tests[src] = set(tests)
        print(f"  {len(already_recorded)} test(s) already recorded — will skip their .cov.json files.", flush=True)

    new_files = [p for p in cov_files if _peek_test_name(p) not in already_recorded]
    print(f"Parsing {len(new_files)} new coverage file(s) (of {len(cov_files)} total) ...", flush=True)

    for cov_path in new_files:
        test_name, coverage = parse_cov_json(cov_path)
        if not test_name:
            print(f"  WARNING: no test_name in {cov_path.name}, skipping", flush=True)
            continue

        for rel_src, functions in coverage.items():
            file2tests.setdefault(rel_src, set()).add(test_name)
            for fn in functions:
                func2tests.setdefault(fn, set()).add(test_name)

    print(
        f"  {len(func2tests)} functions, {len(file2tests)} source files indexed.",
        flush=True,
    )

    # JIT-LTO: extend file2tests with kernel sources and matrix files
    jit_sources = load_jit_sources(jit_sources_path)
    if jit_sources:
        print(
            f"Applying JIT-LTO source map ({len(jit_sources)} fragment tags) ...",
            flush=True,
        )
        apply_jit_lto_logs(coverage_dir, jit_sources, file2tests, skip_tests=already_recorded)
    else:
        print(
            "  jit_lto_sources.json not found or empty, skipping JIT-LTO mapping.",
            flush=True,
        )

    # Serialise — sets → sorted lists for stable output
    mapping = {
        "functions": {k: sorted(v) for k, v in sorted(func2tests.items())},
        "files":     {k: sorted(v) for k, v in sorted(file2tests.items())},
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(mapping, f, indent=2)
        f.write("\n")

    print(f"Written: {output_path}", flush=True)
    print(
        f"  {len(mapping['functions'])} function entries, "
        f"{len(mapping['files'])} file entries",
        flush=True,
    )


if __name__ == "__main__":
    main()
